CREATE OR ALTER PROCEDURE SP_MOVIMIENTO_LISTAR
    @DESDE            DATE,
    @HASTA            DATE,
    @TIPO             CHAR(1) = NULL,  -- NULL = ingresos y egresos
    @ID_CATEGORIA     INT     = NULL,  -- NULL = todas
    @INCLUIR_ANULADOS BIT     = 0
AS
BEGIN
    SET NOCOUNT ON;
 
    IF @DESDE > @HASTA
        THROW 50120, N'La fecha inicial no puede ser mayor que la fecha final.', 1;
 
    SELECT ID_MOVIMIENTO, FECHA_MOVIMIENTO, TIPO, GRUPO, CATEGORIA, MONTO, DESCRIPCION, NUM_COMPROBANTE, FORMA_PAGO, ANULADO, MOTIVO_ANULACION, REGISTRADO_POR, FECHA_REGISTRO, ANULADO_POR, FECHA_ANULACION
    FROM VW_MOVIMIENTO
    WHERE FECHA_MOVIMIENTO BETWEEN @DESDE AND @HASTA AND (@TIPO IS NULL OR TIPO = @TIPO) AND (@ID_CATEGORIA IS NULL OR ID_CATEGORIA = @ID_CATEGORIA) AND (@INCLUIR_ANULADOS = 1 OR ANULADO = 0)
    ORDER BY FECHA_MOVIMIENTO DESC, ID_MOVIMIENTO DESC;
END
GO

CREATE OR ALTER PROCEDURE SP_REPORTE_MENSUAL
    @ANIO INT,
    @MES  INT,
    @TIPO CHAR(1) = 'E'
AS
BEGIN
    SET NOCOUNT ON;
 
    IF @TIPO NOT IN ('I', 'E')
        THROW 50200, N'Tipo de reporte no válido.', 1;
 
    IF @MES NOT BETWEEN 1 AND 12
        THROW 50201, N'Mes no válido.', 1;
 
    SELECT GRUPO, CATEGORIA,COUNT(*) AS CANTIDAD, SUM(MONTO) AS TOTAL FROM VW_MOVIMIENTO
    WHERE TIPO = @TIPO AND ANULADO = 0 AND ANIO = @ANIO AND MES = @MES
    GROUP BY GRUPO, CATEGORIA
    ORDER BY GRUPO, CATEGORIA;
END
GO

CREATE OR ALTER PROCEDURE SP_REPORTE_ANUAL
    @ANIO INT,
    @TIPO CHAR(1) = 'E'
AS
BEGIN
    SET NOCOUNT ON;
 
    IF @TIPO NOT IN ('I', 'E')
        THROW 50210, N'Tipo de reporte no válido.', 1;
 
    SELECT GRUPO, CATEGORIA,
        SUM(CASE WHEN MES = 1  THEN MONTO ELSE 0 END) AS ENE,
        SUM(CASE WHEN MES = 2  THEN MONTO ELSE 0 END) AS FEB,
        SUM(CASE WHEN MES = 3  THEN MONTO ELSE 0 END) AS MAR,
        SUM(CASE WHEN MES = 4  THEN MONTO ELSE 0 END) AS ABR,
        SUM(CASE WHEN MES = 5  THEN MONTO ELSE 0 END) AS MAY,
        SUM(CASE WHEN MES = 6  THEN MONTO ELSE 0 END) AS JUN,
        SUM(CASE WHEN MES = 7  THEN MONTO ELSE 0 END) AS JUL,
        SUM(CASE WHEN MES = 8  THEN MONTO ELSE 0 END) AS AGO,
        SUM(CASE WHEN MES = 9  THEN MONTO ELSE 0 END) AS SEP,
        SUM(CASE WHEN MES = 10 THEN MONTO ELSE 0 END) AS OCT,
        SUM(CASE WHEN MES = 11 THEN MONTO ELSE 0 END) AS NOV,
        SUM(CASE WHEN MES = 12 THEN MONTO ELSE 0 END) AS DIC,
        SUM(MONTO) AS TOTAL
    FROM VW_MOVIMIENTO
    WHERE TIPO = @TIPO AND ANULADO = 0 AND ANIO = @ANIO
    GROUP BY GRUPO, CATEGORIA
    ORDER BY GRUPO, CATEGORIA;
END
GO

CREATE OR ALTER PROCEDURE SP_REPORTE_RESUMEN_ANUAL
    @ANIO INT
AS
BEGIN
    SET NOCOUNT ON;
 
    WITH MESES AS (SELECT 1 AS MES UNION ALL SELECT MES + 1 FROM MESES WHERE MES < 12)
    SELECT M.MES,
            ISNULL(SUM(CASE WHEN V.TIPO = 'I' THEN V.MONTO END), 0) AS INGRESOS,
            ISNULL(SUM(CASE WHEN V.TIPO = 'E' THEN V.MONTO END), 0) AS EGRESOS,
            ISNULL(SUM(CASE WHEN V.TIPO = 'I' THEN V.MONTO WHEN V.TIPO = 'E' THEN -V.MONTO END), 0) AS SALDO
    FROM MESES M
    LEFT JOIN VW_MOVIMIENTO V ON V.MES = M.MES AND V.ANIO = @ANIO AND V.ANULADO = 0
    GROUP BY M.MES
    ORDER BY M.MES;
END