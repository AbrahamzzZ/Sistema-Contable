CREATE OR ALTER PROCEDURE SP_REGISTRAR_USUARIO
    @USERNAME NVARCHAR(100),
    @NOMBRE_COMPLETO NVARCHAR(100),
    @CORREO_ELECTRONICO NVARCHAR(150) = NULL,
    @CLAVE NVARCHAR(300)
AS
BEGIN
    SET NOCOUNT ON;
 
    SET @USERNAME = LTRIM(RTRIM(@USERNAME));
    SET @NOMBRE_COMPLETO = LTRIM(RTRIM(@NOMBRE_COMPLETO));
    SET @CORREO_ELECTRONICO = NULLIF(LOWER(LTRIM(RTRIM(@CORREO_ELECTRONICO))), N'');
 
    IF @USERNAME = N'' OR @NOMBRE_COMPLETO = N''
        THROW 50001, N'El usuario y el nombre completo son obligatorios.', 1;
 
    IF NULLIF(@CLAVE, N'') IS NULL
        THROW 50002, N'La clave es obligatoria.', 1;
 
    IF EXISTS (SELECT 1 FROM USUARIO WHERE USERNAME = @USERNAME)
        THROW 50003, N'El nombre de usuario ya existe.', 1;
 
    IF @CORREO_ELECTRONICO IS NOT NULL AND EXISTS (SELECT 1 FROM USUARIO WHERE CORREO_ELECTRONICO = @CORREO_ELECTRONICO)
        THROW 50004, N'El correo ya está registrado.', 1;
 
    INSERT INTO USUARIO (USERNAME, NOMBRE_COMPLETO, CORREO_ELECTRONICO, CLAVE)
    VALUES (@USERNAME, @NOMBRE_COMPLETO, @CORREO_ELECTRONICO, @CLAVE);
 
    SELECT CAST(SCOPE_IDENTITY() AS INT) AS ID_USUARIO;
END
GO

