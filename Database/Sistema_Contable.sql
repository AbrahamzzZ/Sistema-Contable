CREATE OR ALTER PROCEDURE SP_USUARIO_CAMBIAR_ESTADO
    @ID_USUARIO INT,
    @ACTIVO BIT,
    @ID_USUARIO_SESION INT 
AS
BEGIN
    SET NOCOUNT ON;
 
    IF NOT EXISTS (SELECT 1 FROM USUARIO WHERE ID_USUARIO = @ID_USUARIO)
        THROW 50030, N'El usuario no existe.', 1;
 
    IF @ACTIVO = 0 AND @ID_USUARIO = @ID_USUARIO_SESION
        THROW 50031, N'No puede desactivar su propio usuario.', 1;
 
    IF @ACTIVO = 0 AND NOT EXISTS (SELECT 1 FROM USUARIO WHERE ACTIVO = 1 AND ID_USUARIO <> @ID_USUARIO)
        THROW 50032, N'No se puede desactivar el último usuario activo.', 1;
 
    UPDATE USUARIO SET ACTIVO = @ACTIVO WHERE ID_USUARIO = @ID_USUARIO;
END
GO

