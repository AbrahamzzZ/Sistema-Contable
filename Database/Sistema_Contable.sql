-- TABLA USUARIO
CREATE TABLE USUARIO (
    ID_USUARIO INT PRIMARY KEY IDENTITY,
    USERNAME NVARCHAR(100) NOT NULL UNIQUE,
    NOMBRE_COMPLETO NVARCHAR(100) NOT NULL,
    CLAVE NVARCHAR(300) NOT NULL,
    CORREO_ELECTRONICO NVARCHAR(150) NULL,
    ACTIVO BIT NOT NULL DEFAULT 1,
    ULTIMO_ACCESO DATETIME NULL,
    FECHA_CREACION DATETIME NULL DEFAULT GETDATE()
);
GO

-- TABLA CATEGORIA
CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT PRIMARY KEY IDENTITY,
    NOMBRE NVARCHAR(100) NOT NULL,
    TIPO CHAR(1) NOT NULL CHECK (TIPO IN ('I','E')),
    ID_PADRE INT REFERENCES CATEGORIA(ID_CATEGORIA),
    ORDEN INT NOT NULL DEFAULT 0,
    ACTIVO BIT NOT NULL DEFAULT 1,
    CONSTRAINT UQ_CATEGORIA_PADRE_NOMBRE UNIQUE (ID_PADRE, NOMBRE)
);
GO

-- TABLA MOVIMIENTO
CREATE TABLE MOVIMIENTO (
    ID_MOVIMIENTO INT PRIMARY KEY IDENTITY,
    FECHA_MOVIMIENTO DATE NOT NULL,
    ID_CATEGORIA INT NOT NULL REFERENCES CATEGORIA(ID_CATEGORIA),
    MONTO DECIMAL(12,2) NOT NULL CHECK (MONTO > 0),
    DESCRIPCION NVARCHAR(250) NULL,
    NUM_COMPROBANTE NVARCHAR(50) NULL,
    FORMA_PAGO VARCHAR(20) NOT NULL CHECK (FORMA_PAGO IN ('EFECTIVO', 'TRANSFERENCIA', 'DEPOSITO')),
    ANULADO BIT NOT NULL DEFAULT 0,
    MOTIVO_ANULACION NVARCHAR(250) NULL,
    USUARIO_REGISTRO INT NOT NULL REFERENCES USUARIO(ID_USUARIO),
    FECHA_REGISTRO DATETIME NOT NULL DEFAULT GETDATE(),
    USUARIO_ANULACION INT NULL REFERENCES USUARIO(ID_USUARIO),
    FECHA_ANULACION DATETIME NULL
);
GO

--ÍNDICE
CREATE INDEX IX_MOVIMIENTO_FECHA ON MOVIMIENTO (FECHA_MOVIMIENTO) INCLUDE (ID_CATEGORIA, MONTO, ANULADO);
GO

--VISTA
CREATE OR ALTER VIEW VW_MOVIMIENTO
AS
SELECT  m.ID_MOVIMIENTO, m.FECHA_MOVIMIENTO, YEAR(m.FECHA_MOVIMIENTO) AS ANIO, MONTH(m.FECHA_MOVIMIENTO) AS MES,
        c.TIPO, g.NOMBRE AS GRUPO, c.NOMBRE AS CATEGORIA, m.ID_CATEGORIA,
        m.MONTO, m.DESCRIPCION, m.NUM_COMPROBANTE, m.FORMA_PAGO,
        m.ANULADO, m.MOTIVO_ANULACION,
        u.NOMBRE_COMPLETO AS REGISTRADO_POR, m.FECHA_REGISTRO,
        us.NOMBRE_COMPLETO AS ANULADO_POR, m.FECHA_ANULACION
FROM MOVIMIENTO m
JOIN CATEGORIA c  ON c.ID_CATEGORIA = m.ID_CATEGORIA
JOIN CATEGORIA g ON g.ID_CATEGORIA = c.ID_PADRE
JOIN USUARIO u  ON u.ID_USUARIO = m.USUARIO_REGISTRO
LEFT JOIN USUARIO us ON us.ID_USUARIO = m.USUARIO_ANULACION;
GO

