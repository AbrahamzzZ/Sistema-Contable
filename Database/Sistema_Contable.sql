CREATE OR ALTER PROCEDURE SP_CATEGORIA_INSERTAR
    @NOMBRE NVARCHAR(100),
    @TIPO CHAR(1) = NULL,
    @ID_PADRE INT = NULL,
    @ORDEN INT = NULL 
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
 
    DECLARE @ID_CATEGORIA INT;
 
    SET @NOMBRE = LTRIM(RTRIM(@NOMBRE));
 
    IF NULLIF(@NOMBRE, N'') IS NULL
        THROW 50300, N'El nombre es obligatorio.', 1;
 
    IF @ID_PADRE IS NULL
    BEGIN
        -- Es un GRUPO
        IF @TIPO IS NULL OR @TIPO NOT IN ('I', 'E')
            THROW 50301, N'Indique si el grupo es de ingreso o de egreso.', 1;
 
        SET @NOMBRE = UPPER(@NOMBRE);
    END
    ELSE
    BEGIN
        -- Es una CATEGORÍA: el padre debe ser un grupo activo
        IF NOT EXISTS (SELECT 1 FROM CATEGORIA WHERE ID_CATEGORIA = @ID_PADRE AND ID_PADRE IS NULL AND ACTIVO = 1)
            THROW 50302, N'El grupo seleccionado no existe o está inactivo.', 1;
 
        SELECT @TIPO = TIPO FROM CATEGORIA WHERE ID_CATEGORIA = @ID_PADRE;
    END
 
    IF EXISTS (SELECT 1 FROM CATEGORIA WHERE NOMBRE = @NOMBRE AND ((@ID_PADRE IS NULL AND ID_PADRE IS NULL) OR ID_PADRE = @ID_PADRE))
        THROW 50303, N'Ya existe una categoría con ese nombre en el mismo grupo.', 1;
 
    IF @ORDEN IS NULL
        SELECT @ORDEN = ISNULL(MAX(ORDEN), 0) + 1 FROM CATEGORIA 
        WHERE ((@ID_PADRE IS NULL AND ID_PADRE IS NULL) OR ID_PADRE = @ID_PADRE) AND ORDEN < 99;
 
    BEGIN TRY
        BEGIN TRANSACTION;
 
        INSERT INTO CATEGORIA (NOMBRE, TIPO, ID_PADRE, ORDEN)
        VALUES (@NOMBRE, @TIPO, @ID_PADRE, @ORDEN);
 
        SET @ID_CATEGORIA = CAST(SCOPE_IDENTITY() AS INT);
 
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;
 
    SELECT @ID_CATEGORIA AS ID_CATEGORIA;
END
GO

CREATE OR ALTER PROCEDURE SP_CATEGORIA_ACTUALIZAR
    @ID_CATEGORIA INT,
    @NOMBRE NVARCHAR(100),
    @ORDEN INT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
 
    DECLARE @ID_PADRE INT;
 
    SET @NOMBRE = LTRIM(RTRIM(@NOMBRE));
 
    IF NOT EXISTS (SELECT 1 FROM CATEGORIA WHERE ID_CATEGORIA = @ID_CATEGORIA)
        THROW 50310, N'La categoría no existe.', 1;
 
    IF NULLIF(@NOMBRE, N'') IS NULL
        THROW 50311, N'El nombre es obligatorio.', 1;
 
    SELECT @ID_PADRE = ID_PADRE FROM CATEGORIA WHERE ID_CATEGORIA = @ID_CATEGORIA;
 
    IF @ID_PADRE IS NULL
        SET @NOMBRE = UPPER(@NOMBRE);
 
    IF EXISTS (SELECT 1 FROM CATEGORIA WHERE NOMBRE = @NOMBRE AND ID_CATEGORIA <> @ID_CATEGORIA AND ((@ID_PADRE IS NULL AND ID_PADRE IS NULL) OR ID_PADRE = @ID_PADRE))
        THROW 50312, N'Ya existe una categoría con ese nombre en el mismo grupo.', 1;
 
    BEGIN TRY
        BEGIN TRANSACTION;
 
        UPDATE CATEGORIA SET NOMBRE = @NOMBRE, ORDEN = ISNULL(@ORDEN, ORDEN) WHERE ID_CATEGORIA = @ID_CATEGORIA;
 
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;
END
GO

CREATE OR ALTER PROCEDURE SP_CATEGORIA_CAMBIAR_ESTADO
    @ID_CATEGORIA INT,
    @ACTIVO BIT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
 
    DECLARE @ID_PADRE INT;
 
    IF NOT EXISTS (SELECT 1 FROM CATEGORIA WHERE ID_CATEGORIA = @ID_CATEGORIA)
        THROW 50320, N'La categoría no existe.', 1;
 
    SELECT @ID_PADRE = ID_PADRE FROM CATEGORIA WHERE ID_CATEGORIA = @ID_CATEGORIA;
 
    -- No se activa una categoría si su grupo está inactivo
    IF @ACTIVO = 1 AND @ID_PADRE IS NOT NULL AND EXISTS (SELECT 1 FROM CATEGORIA WHERE ID_CATEGORIA = @ID_PADRE AND ACTIVO = 0)
        THROW 50321, N'Active primero el grupo al que pertenece esta categoría.', 1;
 
    BEGIN TRY
        BEGIN TRANSACTION;
 
        UPDATE CATEGORIA
        SET ACTIVO = @ACTIVO
        WHERE ID_CATEGORIA = @ID_CATEGORIA;
 
        -- Si es un grupo y se desactiva, se desactivan sus categorías
        IF @ID_PADRE IS NULL AND @ACTIVO = 0
            UPDATE CATEGORIA SET ACTIVO = 0 WHERE ID_PADRE = @ID_CATEGORIA;
 
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;
END
GO

CREATE OR ALTER PROCEDURE SP_MOVIMIENTO_INSERTAR
    @FECHA_MOVIMIENTO DATE,
    @ID_CATEGORIA INT,
    @MONTO DECIMAL(12,2),
    @DESCRIPCION NVARCHAR(250) = NULL,
    @NUM_COMPROBANTE NVARCHAR(50)  = NULL,
    @FORMA_PAGO VARCHAR(20),
    @USUARIO_REGISTRO INT
AS
BEGIN
    SET NOCOUNT ON;
 
    SET @DESCRIPCION = NULLIF(LTRIM(RTRIM(@DESCRIPCION)), N'');
    SET @NUM_COMPROBANTE = NULLIF(LTRIM(RTRIM(@NUM_COMPROBANTE)), N'');
    SET @FORMA_PAGO = UPPER(LTRIM(RTRIM(@FORMA_PAGO)));
 
    -- Solo categorías finales y activas
    IF NOT EXISTS (SELECT 1 FROM CATEGORIA WHERE ID_CATEGORIA = @ID_CATEGORIA AND ID_PADRE IS NOT NULL AND ACTIVO = 1)
        THROW 50100, N'Seleccione una categoría válida.', 1;
 
    -- En "Otros" / "Otro" la descripción es obligatoria
    IF @DESCRIPCION IS NULL AND EXISTS (SELECT 1 FROM CATEGORIA WHERE ID_CATEGORIA = @ID_CATEGORIA AND NOMBRE IN (N'Otros', N'Otro'))
        THROW 50101, N'La descripción es obligatoria para la categoría "Otros".', 1;
 
    IF @MONTO IS NULL OR @MONTO <= 0
        THROW 50102, N'El monto debe ser mayor a cero.', 1;
 
    IF @FECHA_MOVIMIENTO > CAST(GETDATE() AS DATE)
        THROW 50103, N'La fecha del movimiento no puede ser futura.', 1;
 
    IF @FORMA_PAGO NOT IN ('EFECTIVO', 'TRANSFERENCIA', 'DEPOSITO')
        THROW 50104, N'Forma de pago no válida.', 1;
 
    IF NOT EXISTS (SELECT 1 FROM USUARIO WHERE ID_USUARIO = @USUARIO_REGISTRO AND ACTIVO = 1)
        THROW 50105, N'Usuario de registro no válido.', 1;
 
    SET XACT_ABORT ON; 
 
    DECLARE @ID_MOVIMIENTO INT;
 
    BEGIN TRY
        BEGIN TRANSACTION;
 
        INSERT INTO MOVIMIENTO (FECHA_MOVIMIENTO, ID_CATEGORIA, MONTO, DESCRIPCION,NUM_COMPROBANTE, FORMA_PAGO, USUARIO_REGISTRO)
        VALUES (@FECHA_MOVIMIENTO, @ID_CATEGORIA, @MONTO, @DESCRIPCION, @NUM_COMPROBANTE, @FORMA_PAGO, @USUARIO_REGISTRO);
 
        SET @ID_MOVIMIENTO = CAST(SCOPE_IDENTITY() AS INT);
 
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;  
    END CATCH;
 
    SELECT @ID_MOVIMIENTO AS ID_MOVIMIENTO;
END
GO
 
CREATE OR ALTER PROCEDURE SP_MOVIMIENTO_ANULAR
    @ID_MOVIMIENTO     INT,
    @MOTIVO_ANULACION  NVARCHAR(250),
    @USUARIO_ANULACION INT
AS
BEGIN
    SET NOCOUNT ON;
 
    SET @MOTIVO_ANULACION = NULLIF(LTRIM(RTRIM(@MOTIVO_ANULACION)), N'');
 
    IF @MOTIVO_ANULACION IS NULL
        THROW 50110, N'Debe indicar el motivo de la anulación.', 1;
 
    IF NOT EXISTS (SELECT 1 FROM USUARIO WHERE ID_USUARIO = @USUARIO_ANULACION AND ACTIVO = 1)
        THROW 50111, N'Usuario de anulación no válido.', 1;
 
    SET XACT_ABORT ON;
 
    BEGIN TRY
        BEGIN TRANSACTION;
 
        UPDATE MOVIMIENTO
        SET ANULADO = 1, MOTIVO_ANULACION = @MOTIVO_ANULACION, USUARIO_ANULACION = @USUARIO_ANULACION, FECHA_ANULACION = GETDATE()
        WHERE ID_MOVIMIENTO = @ID_MOVIMIENTO AND ANULADO = 0;
 
        IF @@ROWCOUNT = 0
            THROW 50112, N'El movimiento no existe o ya está anulado.', 1;
 
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;
END
GO
 
