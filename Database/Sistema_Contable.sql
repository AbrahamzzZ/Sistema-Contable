CREATE OR ALTER PROCEDURE SP_USUARIO_ACTUALIZAR
    @ID_USUARIO INT,
    @NOMBRE_COMPLETO NVARCHAR(100),
    @CORREO_ELECTRONICO NVARCHAR(150) = NULL
AS
BEGIN
    SET NOCOUNT ON;
 
    SET @NOMBRE_COMPLETO = LTRIM(RTRIM(@NOMBRE_COMPLETO));
    SET @CORREO_ELECTRONICO = NULLIF(LOWER(LTRIM(RTRIM(@CORREO_ELECTRONICO))), N'');
 
    IF NOT EXISTS (SELECT 1 FROM USUARIO WHERE ID_USUARIO = @ID_USUARIO)
        THROW 50010, N'El usuario no existe.', 1;
 
    IF @NOMBRE_COMPLETO = N''
        THROW 50011, N'El nombre completo es obligatorio.', 1;
 
    IF @CORREO_ELECTRONICO IS NOT NULL AND EXISTS (SELECT 1 FROM USUARIO WHERE CORREO_ELECTRONICO = @CORREO_ELECTRONICO AND ID_USUARIO <> @ID_USUARIO)
        THROW 50012, N'El correo ya está registrado por otro usuario.', 1;
 
    UPDATE USUARIO SET NOMBRE_COMPLETO = @NOMBRE_COMPLETO, CORREO_ELECTRONICO = @CORREO_ELECTRONICO WHERE ID_USUARIO = @ID_USUARIO;
END
GO

